class _ReportSection extends StatelessWidget {
  final String   title;
  final IconData icon;
  final Color    iconColor;
  final Widget   child;
  const _ReportSection({
    required this.title, required this.icon,
    required this.iconColor, required this.child,
  });

  @override
  Widget build(BuildContext context) => Container(
    width: double.infinity,
    decoration: BoxDecoration(
      color: AppTheme.cardBg,
      borderRadius: BorderRadius.circular(16),
      boxShadow: AppTheme.cardShadow,
    ),
    child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
      Padding(
        padding: const EdgeInsets.fromLTRB(14, 12, 14, 8),
        child: Row(children: [
          Icon(icon, size: 16, color: iconColor),
          const SizedBox(width: 8),
          Text(title, style: const TextStyle(fontSize: 13,
              fontWeight: FontWeight.w800, color: AppTheme.textPrimary)),
        ]),
      ),
      const Divider(height: 1, indent: 14, endIndent: 14),
      Padding(padding: const EdgeInsets.all(14), child: child),
    ]),
  );
}

class _ReportRow extends StatelessWidget {
  final String label, value;
  const _ReportRow(this.label, this.value);
  @override
  Widget build(BuildContext context) => Padding(
    padding: const EdgeInsets.only(bottom: 4),
    child: Row(children: [
      Text('$label: ', style: const TextStyle(fontSize: 11,
          color: AppTheme.textSecondary)),
      Text(value, style: const TextStyle(fontSize: 11,
          fontWeight: FontWeight.w700, color: AppTheme.textPrimary)),
    ]),
  );
}

class _PollChip extends StatelessWidget {
  final String  name;
  final double? value;
  final String  unit;
  const _PollChip(this.name, this.value, this.unit);
  @override
  Widget build(BuildContext context) => Container(
    padding: const EdgeInsets.symmetric(horizontal: 10, vertical: 6),
    decoration: BoxDecoration(
      color: AppTheme.scaffoldBg,
      borderRadius: BorderRadius.circular(8),
      border: Border.all(color: AppTheme.textLight.withOpacity(0.50)),
    ),
    child: Column(children: [
      Text(name, style: const TextStyle(fontSize: 9,
          color: AppTheme.textSecondary)),
      Text(value != null ? '${value!.toStringAsFixed(1)} $unit' : '—',
          style: const TextStyle(fontSize: 11,
              fontWeight: FontWeight.w700, color: AppTheme.textPrimary)),
    ]),
  );
}

class _StatBadge extends StatelessWidget {
  final String label, value;
  final Color  color;
  const _StatBadge(this.label, this.value, this.color);
  @override
  Widget build(BuildContext context) => Container(
    padding: const EdgeInsets.symmetric(horizontal: 12, vertical: 6),
    decoration: BoxDecoration(
      color: color.withOpacity(0.08),
      borderRadius: BorderRadius.circular(10),
      border: Border.all(color: color.withOpacity(0.25)),
    ),
    child: Column(children: [
      Text(label, style: const TextStyle(
          fontSize: 9, color: AppTheme.textSecondary)),
      Text(value, style: TextStyle(fontSize: 14,
          fontWeight: FontWeight.w800, color: color)),
    ]),
  );
}
